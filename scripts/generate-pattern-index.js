#!/usr/bin/env node
/**
 * BAM v3: Generate data/patterns/_index.md from bam-patterns.csv
 *
 * Output:
 *   - src-v2/data/patterns/_index.md (shortcode lookup table)
 *   - Stats summary on stdout
 *
 * Usage: node scripts/generate-pattern-index.js
 */

const fs = require('fs');
const path = require('path');

const CSV_PATH = path.join(__dirname, '..', 'src-v2', 'data', 'bam-patterns.csv');
const OUTPUT_PATH = path.join(__dirname, '..', 'src-v2', 'data', 'patterns', '_index.md');

// Naive CSV row parser handling quoted fields
function parseRow(line) {
  const fields = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c === '"' && line[i + 1] === '"') {
      current += '"';
      i++;
    } else if (c === '"') {
      inQuotes = !inQuotes;
    } else if (c === ',' && !inQuotes) {
      fields.push(current);
      current = '';
    } else {
      current += c;
    }
  }
  fields.push(current);
  return fields;
}

const csvText = fs.readFileSync(CSV_PATH, 'utf-8');
const lines = csvText.split(/\r?\n/);
const header = parseRow(lines[0]);

const idIdx = header.indexOf('pattern_id');
const nameIdx = header.indexOf('name');
const catIdx = header.indexOf('category');
const intentIdx = header.indexOf('intent');
const qgIdx = header.indexOf('verification_gate');
const codeIdx = header.indexOf('shortcode');

const patterns = [];
const byCategory = {};

for (let i = 1; i < lines.length; i++) {
  if (!lines[i].trim()) continue;
  const f = parseRow(lines[i]);
  if (f.length < header.length) continue;

  const p = {
    id: f[idIdx],
    name: f[nameIdx],
    category: f[catIdx],
    intent: f[intentIdx],
    qg: f[qgIdx],
    code: f[codeIdx],
  };
  patterns.push(p);

  if (p.code) {
    byCategory[p.category] = byCategory[p.category] || [];
    byCategory[p.category].push(p);
  }
}

const total = patterns.length;
const withCode = patterns.filter((p) => p.code).length;
console.log(`Total patterns:    ${total}`);
console.log(`With shortcode:    ${withCode}`);
console.log(`Without shortcode: ${total - withCode}`);
console.log(`Categories:        ${Object.keys(byCategory).length}`);

// Generate _index.md
let md = `---
type: bam-pattern-shortcode-index
generated_from: bam-patterns.csv
generated: ${new Date().toISOString().split('T')[0]}
total_patterns: ${total}
patterns_with_shortcode: ${withCode}
---

# BAM Pattern Shortcode Index

> Quick lookup table for BAM patterns by shortcode.
> When a BAM persona references "ZTI" or "ZAO" etc., use this index to resolve to the full pattern document.

## Lookup Table (by Shortcode)

| Shortcode | Pattern | Category | Intent | Quality Gate | File |
|---|---|---|---|---|---|
`;

const sortedByCode = patterns.filter((p) => p.code).sort((a, b) => a.code.localeCompare(b.code));
for (const p of sortedByCode) {
  const intent = (p.intent || '').replace(/\|/g, '\\|').slice(0, 60);
  const fileName = p.id + '.md';
  md += `| **${p.code}** | ${p.name} | ${p.category} | ${intent} | ${p.qg || '-'} | [\`${fileName}\`](./${fileName}) |\n`;
}

md += `\n## Lookup Table (by Category)\n\n`;

const categories = Object.keys(byCategory).sort();
for (const cat of categories) {
  md += `### ${cat}\n\n`;
  md += `| Shortcode | Pattern | Intent | QG |\n|---|---|---|---|\n`;
  for (const p of byCategory[cat].sort((a, b) => a.code.localeCompare(b.code))) {
    const intent = (p.intent || '').replace(/\|/g, '\\|').slice(0, 60);
    md += `| **${p.code}** | [${p.name}](./${p.id}.md) | ${intent} | ${p.qg || '-'} |\n`;
  }
  md += `\n`;
}

md += `\n## Patterns Without Shortcode (${total - withCode})\n\n`;
md += `These patterns are documented but don't yet have a registered shortcode. They are accessible by file name only.\n\n`;
md += `| Pattern | Category | File |\n|---|---|---|\n`;

for (const p of patterns.filter((x) => !x.code).sort((a, b) => a.id.localeCompare(b.id))) {
  md += `| ${p.name} | ${p.category} | [\`${p.id}.md\`](./${p.id}.md) |\n`;
}

md += `\n---\n\n*Generated by \`scripts/generate-pattern-index.js\`. Regenerate when \`bam-patterns.csv\` changes.*\n`;

fs.writeFileSync(OUTPUT_PATH, md, 'utf-8');
console.log(`\nWrote: ${OUTPUT_PATH}`);
console.log(`Length: ${md.length} bytes, ${md.split('\n').length} lines`);